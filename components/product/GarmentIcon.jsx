const DEFAULT_GARMENT = GARMENTS.Shirt

/**
 * @param {string} category - kategori produk (Hoodie, Shirt, Tops, Pants, Accessories, Essentials)
 * @param {string} fill - warna base garmen (value '1' di grid)
 * @param {string} shade - warna shading (value '2')
 * @param {string} detail - warna detail/aksen kecil (value '3')
 * @param {number} scale - ukuran tiap pixel dalam px
 */
export default function GarmentIcon({ category, fill = '#FFFFFF', shade = 'rgba(0,0,0,0.18)', detail = '#FF2D9B', scale = 6 }) {
  const grid = GARMENTS[category] || DEFAULT_GARMENT
  const colorOf = { 1: fill, 2: shade, 3: detail }
  const s = scale
  const size = grid.length
  return (
    <svg
      width={size * s}
      height={size * s}
      viewBox={`0 0 ${size * s} ${size * s}`}
      style={{ imageRendering: 'pixelated', display: 'block' }}
      aria-hidden="true"
    >
      {grid.map((row, r) =>
        row.map((v, c) =>
          v ? <rect key={`${r}-${c}`} x={c * s} y={r * s} width={s} height={s} fill={colorOf[v]} /> : null
        )
      )}
    </svg>
  )
}
